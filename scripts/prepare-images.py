#!/usr/bin/env python3
"""
Turns the raw photos in new-images/ into optimized WebP files for the site
and writes src/lib/imageMeta.ts (width/height + tiny blur placeholder per image).

Usage (from project root):  python3 scripts/prepare-images.py
Requires: pip install pillow
Add or rename photos in new-images/ (hero) or new-images/services/, run again.
"""
import base64, io, json, os, re
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "new-images")

# source filename -> (output slug, long-edge px)
HERO = {
    "9462bb72-e8ea-40d9-ab5b-5c18b296203c.png": "kareem-stage",
    "5A30E4D4-8B62-4F5A-B42D-54D43B6F53E7.png": "jewelry",
    "Cinematic Studio Shoot in Burgundy Accents.png": "studio",
    "clinics.png": "clinics",
    "constructions.png": "construction",
    "corporate.png": "corporate",
    "cosmetics-463E-B3A7-3D2C4EE6CB11.png": "cosmetics",
    "furnitures.png": "interiors",
    "real estate_39_19 PM.png": "real-estate",
}
SERVICES = {
    "Advertising.png": "advertising",
    "Digital solutions.jpg": "digital-solutions",
    "Performance marketing.png": "performance-marketing",
    "Personal branding-3AD7E4C21026.png": "personal-branding",
    "Business consultation.png": "business-consultation",
    "video production.png": "video-production",
}

def blur_data_url(im):
    t = im.copy()
    t.thumbnail((16, 16))
    buf = io.BytesIO()
    t.convert("RGB").save(buf, "JPEG", quality=60)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()

def convert(src_path, out_path, long_edge, quality):
    im = Image.open(src_path).convert("RGB")
    im.thumbnail((long_edge, long_edge), Image.LANCZOS)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    im.save(out_path, "WEBP", quality=quality, method=6)
    return im

meta = {}
for name, slug in HERO.items():
    out = os.path.join(ROOT, "public", "hero", slug + ".webp")
    im = convert(os.path.join(SRC, name), out, 1400, 84)
    meta[f"/hero/{slug}.webp"] = dict(w=im.width, h=im.height, blur=blur_data_url(im))
    print("hero", slug, im.size, os.path.getsize(out) // 1024, "KB")
for name, slug in SERVICES.items():
    out = os.path.join(ROOT, "public", "services", slug + ".webp")
    im = convert(os.path.join(SRC, "services", name), out, 1920, 80)
    meta[f"/services/{slug}.webp"] = dict(w=im.width, h=im.height, blur=blur_data_url(im))
    print("service", slug, im.size, os.path.getsize(out) // 1024, "KB")

lines = ["// AUTO-GENERATED by scripts/prepare-images.py — do not edit by hand.",
         "export const imageMeta: Record<string, { w: number; h: number; blur: string }> = {"]
for k, v in meta.items():
    lines.append(f'  "{k}": {{ w: {v["w"]}, h: {v["h"]}, blur: "{v["blur"]}" }},')
lines.append("};\n")
with open(os.path.join(ROOT, "src", "lib", "imageMeta.ts"), "w") as f:
    f.write("\n".join(lines))
print("wrote src/lib/imageMeta.ts")
